/**
 * Writes src/icons.generated.ts: the path data of the Material Symbols Rounded icons StoryStage uses
 * (weight 400, outline and filled), from @material-symbols/svg-400 (Apache-2.0, decision 0031).
 * Only the icons listed here ship, as inline SVG: no icon font to download on a 4 GB Chromebook.
 *
 * Run `pnpm --filter @storystage/ui icons` after changing the list.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Icon names as Material Symbols spells them. Keep in alphabetical order. */
export const ICON_NAMES = [
  '360',
  'add',
  'add_photo_alternate',
  'category',
  'check_circle',
  'chevron_left',
  'chevron_right',
  'close',
  'deck',
  'description',
  'download',
  'drag_indicator',
  'draw',
  'edit',
  'edit_note',
  'extension',
  'flag',
  'fullscreen',
  'gesture',
  'groups',
  'handyman',
  'headset_mic',
  'hourglass_empty',
  'info',
  'inventory_2',
  'ios_share',
  'keep', // the pin on a script line (was push_pin)
  'landscape',
  'lock',
  'mic',
  'photo_camera',
  'play_arrow',
  'radio_button_unchecked',
  'replay',
  'school',
  'settings',
  'stop',
  'theaters',
  'undo',
  'videocam',
  'view_in_ar',
] as const;

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, '..', 'package.json'));
const root = dirname(require.resolve('@material-symbols/svg-400/package.json'));

function read(file: string): { viewBox: string; d: string } {
  const svg = readFileSync(join(root, 'rounded', file), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!viewBox || paths.length === 0) throw new Error(`No path in ${file}`);
  return { viewBox, d: paths.join(' ') };
}

const entries = ICON_NAMES.map((name) => {
  const outline = read(`${name}.svg`);
  const filled = read(`${name}-fill.svg`);
  if (outline.viewBox !== filled.viewBox)
    throw new Error(`${name}: outline and filled differ in size`);
  return { name, viewBox: outline.viewBox, outline: outline.d, filled: filled.d };
});
const viewBoxes = new Set(entries.map((e) => e.viewBox));
if (viewBoxes.size !== 1) throw new Error(`Icons differ in viewBox: ${[...viewBoxes].join(', ')}`);

const body = entries
  .map((e) => `  '${e.name}': {\n    outline: '${e.outline}',\n    filled: '${e.filled}',\n  },`)
  .join('\n');

writeFileSync(
  join(here, '..', 'src', 'icons.generated.ts'),
  `// Generated by scripts/icons.ts from @material-symbols/svg-400 (Material Symbols Rounded, Apache-2.0).
// Do not edit: change the list in scripts/icons.ts and run \`pnpm --filter @storystage/ui icons\`.

export const ICON_VIEWBOX = '${[...viewBoxes][0]}';

export const ICONS = {
${body}
} as const;

export type IconName = keyof typeof ICONS;
`,
);
console.log(`Wrote ${entries.length} icons.`);
